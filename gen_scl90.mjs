// Generates scl90.data.js from the SCL-90-main JSON so the 90 items and 12
// dimensions (with their diagnostic bands) are transcribed without error.
// Run:  node gen_scl90.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = 'C:/Users/wjz-s/Downloads/MMPI_2_Grader-master/MMPI_2_Grader-master/SCL-90-main/data/SCL-90.json';
const o = JSON.parse(readFileSync(src, 'utf8'));

const zh = [];
for (let i = 1; i <= 90; i += 1) zh.push(o.questions[String(i)].question);

function parseBands(diagnosis) {
  const count = Object.keys(diagnosis).length;
  // 严重度标签随分段数变化：2 段（总分 / 总平均分）为 正常/异常，
  // 3 段（9 因子 + 其他）为 正常/轻度~中度/偏重~严重。
  const SEV = {
    1: ['正常'],
    2: ['正常', '异常（升高）'],
    3: ['正常', '轻度~中度', '偏重~严重'],
    4: ['正常', '轻度', '中度', '偏重'],
  };
  const labels = SEV[count] || SEV[4];
  return Object.entries(diagnosis).map(([key, text], idx) => {
    const minInc = key[0] === '[';
    const maxInc = key[key.length - 1] === ']';
    const nums = key.slice(1, -1).split(',').map(Number);
    return { min: nums[0], max: nums[1], minInc, maxInc, severity: labels[idx] || `等级${idx + 1}`, text };
  });
}

const scales = o.direction.map((d, i) => ({
  name: d.name,
  fullName: d.name,
  type: d.type, // 'avg' | 'sum'
  bind: d.bind.map((x) => Number(x)), // [0] means "all 90 items"
  bands: parseBands(d.diagnosis),
  family: 0,
  y: i,
  p: i,
  flat: i,
}));

const LIKERT5 = {
  id: 'likert5',
  type: 'likert',
  levels: [
    { value: 0, label: '没有' },
    { value: 1, label: '很轻' },
    { value: 2, label: '中等' },
    { value: 3, label: '偏重' },
    { value: 4, label: '严重' },
  ],
};

const data = {
  id: 'scl90',
  name: o.name,
  nItems: 90,
  scoreShift: 1, // 内部级别 0..4 -> 得分 1..5
  positiveScore: 2, // 得分 >=2 计为阳性项目
  items: {
    zh: zh.map((s) => s.trim()),
    en: zh.map(() => ''),
    format: Array(90).fill('likert5'),
  },
  formats: { likert5: LIKERT5 },
  scales,
  // 阳性项目数临界（常用 ≥43 为可疑）；仅作提示，不参与计分
  positiveCutoff: 43,
};

const out = `// AUTO-GENERATED by gen_scl90.mjs -- do not edit by hand.
// Source: SCL-90-main/data/SCL-90.json
export const SCL90_DATA = ${JSON.stringify(data, null, 2)};
`;
writeFileSync(new URL('scl90.data.js', import.meta.url), out);
console.log(`wrote scl90.data.js: ${zh.length} items, ${scales.length} scales`);
